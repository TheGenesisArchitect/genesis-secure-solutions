// Bakes data/templates/*.html into lib/templates.ts so the server bundle carries them (no runtime fs reads).
import fs from 'node:fs';
const welcome = fs.readFileSync('data/templates/welcome.html', 'utf8');
fs.writeFileSync('lib/templates.ts', `// Generated by scripts/build-template.mjs. Edit data/templates/welcome.html instead.\nexport const WELCOME_TEMPLATE = ${JSON.stringify(welcome)};\n`);
console.log('lib/templates.ts written');
